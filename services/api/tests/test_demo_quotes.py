@pytest.mark.asyncio
async def test_demo_refine_preserves_manual_lines_and_replaces_ai_lines(
    client: AsyncClient, db: AsyncSession
) -> None:
    manual_line = {
        "description": "My own priced faceplate",
        "quantity": "1",
        "unit": "ea",
        "unit_price": "150.00",
        "ai_generated": False,
    }
    ai_line = {
        "description": "Install double socket (labour per point)",
        "quantity": "2",
        "unit": "hour",
        "unit_price": "65.00",
        "ai_generated": True,
    }
    refined = {
        "line_items": [
            {
                "description": "Install double socket incl. chasing",
                "kind": "labour",
                "unit": "hour",
                "quantity": 3,
                "unit_price": 65.00,
            }
        ],
        "notes": "Refined per instructions",
    }
    with _mock_llm(generated=refined):
        response = await client.post(
            "/demo/quotes/refine",
            json={
                "description": DESCRIPTION,
                "instructions": "Include chasing the walls for the cable runs",
                "line_items": [manual_line, ai_line],
            },
        )
    assert response.status_code == 200, response.text
    body = response.json()
    by_description = {li["description"]: li for li in body["line_items"]}

    # Manual line survives untouched; the AI line was regenerated.
    assert by_description["My own priced faceplate"]["ai_generated"] is False
    assert Decimal(by_description["My own priced faceplate"]["unit_price"]) == Decimal("150.00")
    assert "Install double socket (labour per point)" not in by_description
    refined_line = by_description["Install double socket incl. chasing"]
    assert refined_line["ai_generated"] is True
    assert refined_line["quantity"] == "3"

    # Totals recalculated: (150 + 195) ex-VAT, plus 20% VAT.
    assert Decimal(body["subtotal"]) == Decimal("345.00")
    assert Decimal(body["total"]) == Decimal("414.00")
    assert body["ai"]["notes"] == "Refined per instructions"


