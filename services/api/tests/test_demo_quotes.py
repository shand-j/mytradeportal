DESCRIPTION = "I need two extra double sockets installed in the kitchen walls"

# Labour priced AT the demo tenant rate (£65/hr) so validation's labour snap
# (drift > 20%) does not rewrite it; material is guide-priced (no catalogue).
_GENERATED = {
    "line_items": [
        {
            "description": "Install double socket (labour per point)",
            "kind": "labour",
            "unit": "hour",
            "quantity": 4,
            "unit_price": 65.00,
        },
        {
            "description": "Double socket faceplate and back box",
            "kind": "material",
            "unit": "each",
            "quantity": 2,
            "unit_price": 18.50,
        },
    ],
    "assumptions": ["Assumed standard back boxes already in place"],
    "notes": "Generated by AI",
}

_RETRIEVED: list[dict[str, Any]] = []


@contextmanager
def _mock_llm(generated: dict[str, Any] | None = None, retrieval_status: str = "no_index") -> Any:
    from unittest.mock import AsyncMock, patch

    with (
        patch(
            "app.routers.demo.search_cost_items_with_status",
            new=AsyncMock(return_value=(_RETRIEVED, retrieval_status)),
        ),
        patch(
            "app.routers.demo.generate_quote_from_prompt",
            new=AsyncMock(return_value=generated if generated is not None else _GENERATED),
        ),
    ):
        yield


async def _all_events(db: AsyncSession) -> list[DemoQuoteEvent]:
    rows = await db.execute(select(DemoQuoteEvent))
    return list(rows.scalars().all())


@pytest.mark.asyncio
async def test_demo_generate_returns_line_items_and_ai_metadata(
    client: AsyncClient, db: AsyncSession
) -> None:
    with _mock_llm():
        response = await client.post(
            "/demo/quotes/generate",
            json={
                "description": DESCRIPTION,
                "property_type": "detached_house",
                "utm_source": "landing",
                "utm_medium": "cta",
                "utm_campaign": "beta",
            },
            headers={"user-agent": "pytest-demo/1.0", "referer": "https://example.com/"},
        )

    assert response.status_code == 200, response.text
    body = response.json()
    assert len(body["line_items"]) == 2
    labour = body["line_items"][0]
    assert labour["description"] == "Install double socket (labour per point)"
    assert labour["ai_generated"] is True
    assert Decimal(labour["total"]) == Decimal("260.00")
    # VAT-registered demo business: 20% on the 297.00 subtotal.
    assert Decimal(body["subtotal"]) == Decimal("297.00")
    assert Decimal(body["vat_rate"]) == Decimal("0.20")
    assert Decimal(body["vat_amount"]) == Decimal("59.40")
    assert Decimal(body["total"]) == Decimal("356.40")
    # AI metadata mirrors QuoteRead's ai_* / retrieval_status fields.
    assert body["ai"]["confidence"] is not None
    assert body["ai"]["assumptions"] == ["Assumed standard back boxes already in place"]
    assert body["ai"]["notes"] == "Generated by AI"
    assert body["ai"]["warnings"] == []
    assert body["retrieval_status"] == "no_index"
    assert body["generation_seconds"] >= 0


@pytest.mark.asyncio
async def test_demo_generate_records_event_without_persisting_content(
    client: AsyncClient, db: AsyncSession
) -> None:
    with _mock_llm():
        response = await client.post(
            "/demo/quotes/generate",
            json={
                "description": DESCRIPTION,
                "utm_source": "landing",
            },
            headers={"user-agent": "pytest-demo/1.0"},
        )
    assert response.status_code == 200, response.text

    events = await _all_events(db)
    assert len(events) == 1
    event = events[0]
    assert event.ip_hash
    assert len(event.ip_hash) == 64
    assert event.utm_source == "landing"
    assert event.user_agent == "pytest-demo/1.0"
    assert event.generation_seconds is not None

    # Nothing about the job description or the generated quote may be durable:
    # inspect every column of every row for any fragment of the content.
    sentinel = "extra double sockets installed in the kitchen"
    for row in events:
        for column in DemoQuoteEvent.__table__.columns:
            value = getattr(row, column.name)
            assert sentinel not in str(value), f"description leaked into {column.name}"


