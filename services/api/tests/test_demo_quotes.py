@pytest.mark.asyncio
async def test_demo_generate_event_survives_storage_failure(
    client: AsyncClient,
    db: AsyncSession,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """If the analytics insert fails, the demo response still succeeds."""

    async def _exploding_commit() -> None:
        raise RuntimeError("database is read-only")

    monkeypatch.setattr(db, "commit", _exploding_commit)
    with _mock_llm():
        response = await client.post(
            "/demo/quotes/generate",
            json={"description": DESCRIPTION},
        )
    assert response.status_code == 200, response.text
    # No event row was written, and the failed insert was rolled back.
    assert await _all_events(db) == []


